def test_encode_banana():
    assert bwt_encode("banana") == ("nnbaaa", 3)


def test_decode_banana():
    assert bwt_decode("nnbaaa", 3) == "banana"


def test_encode_mississippi():
    assert bwt_encode("mississippi") == ("pssmipissii", 4)


def test_encode_periodic_abab():
    assert bwt_encode("abab") == ("bbaa", 0)


def test_encode_periodic_aaaa():
    assert bwt_encode("aaaa") == ("aaaa", 0)


def test_encode_single_char():
    assert bwt_encode("a") == ("a", 0)


# ---------------------------------------------------------------------------
# Property tests on random corpora
# ---------------------------------------------------------------------------

CORPUS_SEED = 590063


def _random_corpus():
    rng = random.Random(CORPUS_SEED)
    out = []
    # Periodic strings and single-letter strings pinned explicitly.
    out.extend(["abab", "aaaa", "abcabcabc", "aabbaabb", "b", "ab", "ba"])
    for _ in range(60):
        n = rng.randint(1, 14)
        alpha = rng.choice(["a", "ab", "abc", "abcd"])
        s = "".join(rng.choice(alpha) for _ in range(n))
        out.append(s)
    # Periodic strings generated by repetition.
    for _ in range(20):
        period_len = rng.randint(1, 3)
        period = "".join(rng.choice("ab") for _ in range(period_len))
        reps = rng.randint(2, 4)
        out.append((period * reps)[: rng.randint(1, 14)])
    return out


def test_property_encode_matches_doubling_reference():
    for s in _random_corpus():
        assert bwt_encode(s) == ref_encode_doubling(s), s


def test_property_roundtrip_decode_encode():
    for s in _random_corpus():
        last, idx = bwt_encode(s)
        assert bwt_decode(last, idx) == s, s


def test_property_decode_matches_naive_table_decoder():
    for s in _random_corpus():
        last, idx = bwt_encode(s)
        assert bwt_decode(last, idx) == ref_decode_naive(last, idx), s


def test_tie_break_is_pinned_not_stability():
    # "abab" rotations at equal strings must order by ascending offset.
    assert bwt_encode("abab") == ("bbaa", 0)
    assert bwt_encode("aaaa") == ("aaaa", 0)
    # Rotation-doubling reference agrees on all periodic cases above.
    for s in ["abab", "aaaa", "abcabc", "aabbaabb", "ababab"]:
        assert bwt_encode(s) == ref_encode_doubling(s), s


