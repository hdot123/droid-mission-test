"""Tests for bwt.py -- Burrows-Wheeler Transform acceptance criteria."""

import random

import pytest

from bwt import bwt_decode, bwt_encode

# ---------------------------------------------------------------------------
# Reference implementations (independent of bwt.py)
# ---------------------------------------------------------------------------


def ref_encode_doubling(s: str) -> tuple[str, int]:
    """Reference encode: rotation-doubling-style ordering.

    Ranks of each rotation are computed by repeatedly doubling the ranks of
    paired halves of each rotation (a rotation-doubling scheme, independent
    of building and sorting the rotation strings themselves).  Equal ranks
    mean identical rotations; among equal ranks the smaller offset sorts
    first, pinning the same tie-break rule as the spec.
    """
    n = len(s)
    rank = [ord(c) for c in s]  # initial ranks: characters themselves
    k = 1
    while k < n:
        pairs = sorted((rank[i], rank[(i + k) % n], i) for i in range(n))
        new_rank = {}
        r = 0
        prev = None
        for a, b, i in pairs:
            key = (a, b)
            if key != prev:
                r += 1
                prev = key
            new_rank[i] = r
        rank = [new_rank[i] for i in range(n)]
        k *= 2
    # rank[i] equal <=> rotations i and 0-relative equal (string-wise).
    order = sorted(range(n), key=lambda i: (rank[i], i))
    last_col = "".join(s[(i - 1) % n] for i in order)
    index = order.index(0)
    return last_col, index


def ref_decode_naive(last_col: str, index: int) -> str:
    """Reference decode: prepend-and-sort table (naive, O(n^2 log n))."""
    table = ["" for _ in last_col]
    for _ in last_col:
        table = [c + row for c in last_col]
        table.sort()
    return table[index]


